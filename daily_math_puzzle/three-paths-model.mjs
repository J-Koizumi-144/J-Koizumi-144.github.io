export const sizes = layouts.map((_, i) => i + 1);
export const colors = ['red', 'blue', 'green'];

function turn(p, q, r) {
    return (q[0] - p[0]) * (r[1] - p[1]) - (q[1] - p[1]) * (r[0] - p[0]);
}

function crosses([a, b], [c, d], points) {
    const [p, q, r, s] = [a, b, c, d].map(i => points[i]);
    return turn(p, q, r) * turn(p, q, s) < 0 && turn(r, s, p) * turn(r, s, q) < 0;
}

export function makeBoard(size, variant = 0) {
    const layout = layouts[size - 1]?.[variant];
    if (!Number.isInteger(size) || !layout) throw new RangeError('Unknown board');
    const points = [...corners, ...layout];
    // On these general-position layouts, a maximal noncrossing edge set triangulates the hull.
    const candidates = [];
    for (let b = 3; b < points.length; b++) {
        for (let a = 0; a < b; a++) {
            const length = Math.hypot(points[b][0] - points[a][0], points[b][1] - points[a][1]);
            candidates.push({ pair: [a, b], length });
        }
    }
    candidates.sort((a, b) => a.length - b.length);
    const edges = [];
    for (const {pair} of candidates) {
        if (edges.every(edge => !crosses(pair, edge, points))) edges.push(pair);
    }
    return {points, edges, size, variant, variants: layouts[size - 1].length};
}

// Adjacent touch targets can overlap near a vertex. Pick the nearest actual segment.
export function nearestEdge({edges, points}, x, y) {
    let closest = -1;
    let least = Infinity;
    edges.forEach(([a, b], i) => {
        const [ax, ay] = points[a], [bx, by] = points[b];
        const dx = bx - ax, dy = by - ay;
        const t = Math.max(0, Math.min(1, ((x - ax) * dx + (y - ay) * dy) / (dx * dx + dy * dy)));
        const distance = (x - ax - t * dx) ** 2 + (y - ay - t * dy) ** 2;
        if (distance < least) {
            least = distance;
            closest = i;
        }
    });
    return closest;
}

export function newPainting(board) {
    return {board, paint: Array(board.edges.length).fill(null), history: []};
}

export function paintEdge(state, index, color) {
    if (!Number.isInteger(index) || index < 0 || index >= state.paint.length) return false;
    if (color !== null && !colors.includes(color)) return false;
    const previous = state.paint[index];
    if (color === previous) return false;
    state.history.push({index, previous});
    state.paint[index] = color;
    return true;
}

export function undo(state) {
    const last = state.history.pop();
    if (last) state.paint[last.index] = last.previous;
}

export function coverage({board, paint}) {
    const reached = colors.map((color, corner) => {
        const neighbors = board.points.map(() => []);
        board.edges.forEach(([a, b], index) => {
            if (paint[index] === color) {
                neighbors[a].push(b);
                neighbors[b].push(a);
            }
        });
        const visited = new Set([corner]);
        const pending = [corner];
        while (pending.length) {
            for (const next of neighbors[pending.pop()]) {
                if (!visited.has(next)) {
                    visited.add(next);
                    pending.push(next);
                }
            }
        }
        return visited;
    });
    const counts = reached.map(set => [...set].filter(i => i >= 3).length);
    const complete = paint.every(Boolean) && counts.every(n => n === board.size);
    return {reached, counts, complete};
}
